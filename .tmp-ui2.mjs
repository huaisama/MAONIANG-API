import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const APP = 'http://127.0.0.1:8787';
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const cfg = JSON.parse(fs.readFileSync('data/config.json', 'utf8'));
const port = 9334;
const chrome = spawn(CHROME, ['--headless=new', '--remote-debugging-port=' + port, '--user-data-dir=' + path.join(os.tmpdir(), 'replyapi-ui2-' + Date.now()), '--no-first-run', '--disable-gpu', '--window-size=1440,900', 'about:blank'], { stdio: 'ignore' });
process.on('exit', () => { try { chrome.kill(); } catch {} });
async function waitJson(url) { for (let i = 0; i < 60; i++) { try { const r = await fetch(url); if (r.ok) return await r.json(); } catch {} await new Promise((x) => setTimeout(x, 250)); } throw new Error('no chrome'); }
const list = await waitJson('http://127.0.0.1:' + port + '/json/list');
const page = list.find((t) => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let seq = 0; const pend = new Map(); const errors = [];
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text); };
const send = (method, params = {}) => { const id = ++seq; return new Promise((r) => { pend.set(id, r); ws.send(JSON.stringify({ id, method, params })); }); };
const ev = async (e) => { const r = await send('Runtime.evaluate', { expression: e, returnByValue: true, awaitPromise: true }); return r.result?.result?.value; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url: APP + '/admin' }); await sleep(1200);
console.log('初始:', await ev(`({login:document.querySelector('#loginOverlay').className, items:document.querySelectorAll('.item').length, cookie:document.cookie})`));
console.log('login status:', await ev(`fetch('/admin/api/login',{method:'POST',credentials:'same-origin',headers:{'Content-Type':'application/json'},body:JSON.stringify({password:${JSON.stringify(cfg.adminPassword)}})}).then(r=>r.status)`));
await send('Page.reload'); await sleep(1800);
console.log('reload后:', await ev(`({login:document.querySelector('#loginOverlay').className, settings:document.querySelector('#settingsOverlay').className, items:document.querySelectorAll('.item').length, pwd:!!document.querySelector('#loginPwd')})`));
await ev(`(()=>{const it=document.querySelector('.item'); if(it) it.click(); return 1;})()`); await sleep(600);
console.log('选中后:', await ev(`({login:document.querySelector('#loginOverlay').className, taTop: Math.round(document.querySelector('#respBody')?.getBoundingClientRect().top ?? -1), hasSum: !!document.querySelector('.sum')})`));
const shot = await send('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('preview/admin-summary-wide.png', Buffer.from(shot.result.data, 'base64'));
console.log('errors:', errors);
chrome.kill(); process.exit(0);
